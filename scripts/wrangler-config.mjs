#!/usr/bin/env node
// Writes one instance's wrangler config: wrangler.example.jsonc with the
// per-instance values filled in from the environment. The deploy action
// (.github/actions/deploy) runs it; you can too, to make a local wrangler.jsonc.
//
// Usage: WORKER_NAME=agent-inbox D1_DATABASE_ID=... ACCESS_TEAM_DOMAIN=<team>.cloudflareaccess.com \
//          ACCESS_AUD=... PUBLIC_URL=https://agent-inbox.<subdomain>.workers.dev \
//          [EXTRA_VARS='{"CHANGES_RETENTION_DAYS":"60"}'] \
//          node scripts/wrangler-config.mjs --out wrangler.jsonc [--force]
//
// WORKER_NAME defaults to agent-inbox. The file is written next to the example
// (relative paths in it, like main and migrations_dir, resolve from there).
// Exits 1 without writing anything when a value is missing or malformed.

import { existsSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { instanceConfig, readJsonc } from "./lib/wrangler-config.mjs";
import { REPO_ROOT } from "./lib/wrangler.mjs";

const USAGE = "Usage: D1_DATABASE_ID=… ACCESS_TEAM_DOMAIN=… ACCESS_AUD=… PUBLIC_URL=… [WORKER_NAME=…] [EXTRA_VARS='{…}'] node scripts/wrangler-config.mjs --out FILE [--force]";

export function main(argv, env = process.env) {
  const { values } = parseArgs({ args: argv, options: { out: { type: "string" }, force: { type: "boolean" }, help: { type: "boolean", short: "h" } } });
  if (values.help) {
    console.log(USAGE);
    return 0;
  }
  if (!values.out) {
    console.error(`wrangler-config: --out is required\n${USAGE}`);
    return 2;
  }
  const out = resolve(REPO_ROOT, basename(values.out));
  if (resolve(values.out) !== out) {
    console.error(`wrangler-config: --out must name a file in the repo root (${REPO_ROOT}), next to wrangler.example.jsonc`);
    return 2;
  }
  if (existsSync(out) && !values.force) {
    console.error(`wrangler-config: ${values.out} exists; pass --force to replace it`);
    return 1;
  }
  let vars;
  try {
    vars = env.EXTRA_VARS?.trim() ? JSON.parse(env.EXTRA_VARS) : undefined;
  } catch (err) {
    console.error(`wrangler-config: EXTRA_VARS is not JSON: ${err.message}`);
    return 1;
  }
  let config;
  try {
    config = instanceConfig(readJsonc(resolve(REPO_ROOT, "wrangler.example.jsonc")), {
      name: env.WORKER_NAME?.trim() || undefined,
      databaseId: env.D1_DATABASE_ID,
      accessTeamDomain: env.ACCESS_TEAM_DOMAIN,
      accessAud: env.ACCESS_AUD,
      publicUrl: env.PUBLIC_URL,
      vars,
    });
  } catch (err) {
    console.error(`wrangler-config: ${err.message}`);
    return 1;
  }
  const header = "// Generated by scripts/wrangler-config.mjs from wrangler.example.jsonc; edit the inputs, not this file.\n";
  writeFileSync(out, header + JSON.stringify(config, null, 2) + "\n");
  console.error(`wrangler-config: wrote ${values.out} for Worker ${config.name} at ${config.vars.PUBLIC_URL}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}
